export const getTranslation = (key: string, lang: string, placeholders?: Record<string, string>) => {
  const altKey = key.includes('MORO') ? key.replace(/MORO/g, 'PIMO') : key.replace(/PIMO/g, 'MORO');
  let text = translations[lang]?.[key] || translations[lang]?.[altKey] || translations['English']?.[key] || translations['English']?.[altKey];
  if (!text) return undefined;
  
  if (placeholders) {
    Object.entries(placeholders).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
};
